"""Corpus scope statistics, rendered for the README.

``law-map stats --markdown`` prints the tables between the
``<!-- law-map stats:begin -->`` / ``<!-- law-map stats:end -->`` markers
in README.md; ``--check`` fails when the README copy is stale and
``--write`` refreshes it. Output depends on the corpus only (never on
today's date), so CI can compare it byte for byte.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path

from .model import CATEGORIES, PACKS, Corpus, obligation_groundings, obligation_pack, parse_iso_date

__all__ = ["BEGIN_MARKER", "END_MARKER", "check_block", "render_markdown", "render_text", "replace_block"]

BEGIN_MARKER = "<!-- law-map stats:begin (generated by `law-map stats --markdown`; do not edit) -->"
END_MARKER = "<!-- law-map stats:end -->"

# Binding-level columns: (heading, source types counted).
BINDING_LEVELS: tuple[tuple[str, frozenset[str]], ...] = (
    ("Statute / regulation", frozenset({"statute", "regulation"})),
    ("Case law", frozenset({"precedent"})),
    ("Guidance / standard", frozenset({"guidance", "standard", "model_code"})),
    ("Not a legal source", frozenset({"private_rule", "incident_report"})),
)
JURISDICTION_NAMES = {
    "JP": "Japan",
    "EU": "European Union",
    "US": "United States, incl. states",
    "GB": "United Kingdom",
    "DE": "Germany",
    "KR": "South Korea",
    "CA": "Canada",
}
NONE = "—"


def _jurisdictions(corpus: Corpus) -> list[str]:
    """Jurisdictions by grounding count (descending), ties alphabetical."""
    counts = Counter(str(g.get("jurisdiction")) for ob in corpus.obligations for g in obligation_groundings(ob))
    return sorted(counts, key=lambda j: (-counts[j], j))


def _label(code: str) -> str:
    name = JURISDICTION_NAMES.get(code)
    return f"{name} ({code})" if name else code


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _binding_counts(corpus: Corpus) -> dict[str, Counter[str]]:
    """Per jurisdiction: ``total`` groundings plus one count per binding-level heading."""
    per: dict[str, Counter[str]] = defaultdict(Counter)
    for ob in corpus.obligations:
        for g in obligation_groundings(ob):
            j = str(g.get("jurisdiction"))
            per[j]["total"] += 1
            for heading, types in BINDING_LEVELS:
                if g.get("source_type") in types:
                    per[j][heading] += 1
    return per


def _binding_table(corpus: Corpus, jurisdictions: list[str]) -> list[str]:
    per = _binding_counts(corpus)
    reviewed: dict[str, list[str]] = defaultdict(list)
    due: dict[str, list[str]] = defaultdict(list)
    for ob in corpus.obligations:
        for g in obligation_groundings(ob):
            j = str(g.get("jurisdiction"))
            if parse_iso_date(g.get("reviewed_on")) is not None:
                reviewed[j].append(str(g["reviewed_on"]))
            if parse_iso_date(g.get("review_by")) is not None:
                due[j].append(str(g["review_by"]))
    headings = [h for h, _ in BINDING_LEVELS]
    lines = [
        _row(["Jurisdiction", "Groundings", *headings, "Last checked", "Next review due"]),
        _row(["---", "---:", *["---:"] * len(headings), "---", "---"]),
    ]
    totals: Counter[str] = Counter()
    for j in jurisdictions:
        totals.update(per[j])
        lines.append(
            _row(
                [
                    _label(j),
                    str(per[j]["total"]),
                    *[str(per[j][h]) for h in headings],
                    max(reviewed[j], default=NONE),
                    min(due[j], default=NONE),
                ]
            )
        )
    all_reviewed = [d for j in jurisdictions for d in reviewed[j]]
    all_due = [d for j in jurisdictions for d in due[j]]
    lines.append(
        _row(
            [
                "**Total**",
                f"**{totals['total']}**",
                *[f"**{totals[h]}**" for h in headings],
                max(all_reviewed, default=NONE),
                min(all_due, default=NONE),
            ]
        )
    )
    return lines


def _category_table(corpus: Corpus, jurisdictions: list[str]) -> list[str]:
    categories = sorted(CATEGORIES)
    cells: dict[tuple[str, str], set[str]] = defaultdict(set)
    for ob in corpus.obligations:
        category = str(ob.data.get("category"))
        for g in obligation_groundings(ob):
            cells[(str(g.get("jurisdiction")), category)].add(ob.id)
    lines = [
        _row(["Jurisdiction", *categories]),
        _row(["---", *["---:"] * len(categories)]),
    ]
    for j in jurisdictions:
        lines.append(_row([_label(j), *[str(len(cells[(j, c)]) or NONE) for c in categories]]))
    return lines


def _pack_table(corpus: Corpus) -> list[str]:
    obligations: Counter[str] = Counter()
    groundings: Counter[str] = Counter()
    for ob in corpus.obligations:
        pack = obligation_pack(ob)
        obligations[pack] += 1
        groundings[pack] += len(obligation_groundings(ob))
    lines = [_row(["Pack", "Obligations", "Groundings"]), _row(["---", "---:", "---:"])]
    for pack in PACKS:
        lines.append(_row([f"`{pack}`", str(obligations[pack]), str(groundings[pack])]))
    return lines


def render_markdown(corpus: Corpus) -> str:
    """The README scope block: totals, binding levels, jurisdiction x category, packs."""
    jurisdictions = _jurisdictions(corpus)
    n_groundings = sum(len(obligation_groundings(ob)) for ob in corpus.obligations)
    lines = [
        f"**{len(corpus.obligations)} obligations, {n_groundings} groundings, {len(jurisdictions)} jurisdictions.**",
        "",
        "Groundings by binding level. *Last checked* is the latest `reviewed_on`",
        "(— when none is recorded yet); *next review due* is the earliest `review_by`.",
        "",
        *_binding_table(corpus, jurisdictions),
        "",
        "Obligations with at least one grounding in the jurisdiction, by category",
        "(— marks a gap):",
        "",
        *_category_table(corpus, jurisdictions),
        "",
        "Obligations by pack (an obligation belongs to the pack of its strongest grounding):",
        "",
        *_pack_table(corpus),
    ]
    return "\n".join(lines) + "\n"


def render_text(corpus: Corpus) -> str:
    """One plain line per jurisdiction: grounding counts by binding level."""
    per = _binding_counts(corpus)
    lines = []
    for j in _jurisdictions(corpus):
        counts = per[j]
        detail = ", ".join(f"{h.lower()} {counts[h]}" for h, _ in BINDING_LEVELS)
        lines.append(f"{j}: {counts['total']} grounding(s) ({detail})")
    return "\n".join(lines) + "\n"


def _split(text: str, path: Path) -> tuple[str, str, str]:
    """(before, current block, after) around the stats markers; ValueError when absent."""
    start = text.find(BEGIN_MARKER)
    end = text.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"{path}: missing stats markers {BEGIN_MARKER!r} ... {END_MARKER!r}")
    body_start = start + len(BEGIN_MARKER)
    return text[:body_start], text[body_start:end], text[end:]


def check_block(path: Path, rendered: str) -> bool:
    """True when the marker block in *path* equals *rendered* (blank-line padded)."""
    _before, block, _after = _split(path.read_text(encoding="utf-8"), path)
    return block == f"\n\n{rendered}\n"


def replace_block(path: Path, rendered: str) -> bool:
    """Rewrite the marker block in *path*; True when the file changed."""
    text = path.read_text(encoding="utf-8")
    before, block, after = _split(text, path)
    new = f"{before}\n\n{rendered}\n{after}"
    if new == text:
        return False
    path.write_text(new, encoding="utf-8")
    return True
